"use client"

import { useState, useEffect } from 'react'
import { DigitalPrescription } from '@/components/digital-prescription'
import { QRCodeGenerator } from '@/lib/qr-code-utils'
import { PrescriptionData } from '@/lib/prescription-types'
import { Card, CardContent } from '@/components/ui/card'
import { AlertTriangle, Loader2, ShieldX, QrCode } from 'lucide-react'
import { Button } from '@/components/ui/button'

export default function QRScanPage() {
  const [prescription, setPrescription] = useState<PrescriptionData | null>(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [qrInput, setQrInput] = useState<string>('')

  useEffect(() => {
    // Check if we have QR data from URL parameters
    if (typeof window !== 'undefined') {
      const urlParams = new URLSearchParams(window.location.search)
      const qrData = urlParams.get('data')
      if (qrData) {
        handleQRData(qrData)
      }
    }
  }, [])

  const handleQRData = async (qrData: string) => {
    try {
      setLoading(true)
      setError(null)

      console.log('Processing QR data:', qrData)

      // Try to extract prescription data from QR code
      let prescriptionData = QRCodeGenerator.extractPrescriptionFromQRData(qrData)
      
      if (!prescriptionData) {
        // If QR data is not in our format, try to parse it as JSON
        try {
          const parsedData = JSON.parse(qrData)
          if (parsedData.id) {
            prescriptionData = parsedData
          }
        } catch {
          // If it's a URL, extract the prescription ID
          if (qrData.includes('prescription/digital/')) {
            const match = qrData.match(/prescription\/digital\/([^?]+)/)
            if (match) {
              const prescriptionId = match[1]
              prescriptionData = await loadPrescriptionById(prescriptionId)
            }
          }
        }
      }

      if (!prescriptionData) {
        setError('Invalid QR code. This does not appear to be a valid prescription QR code from Gonstead Chiropractic Clinic.')
        setLoading(false)
        return
      }

      setPrescription(prescriptionData)
      setLoading(false)

    } catch (err) {
      console.error('Error processing QR data:', err)
      setError('Failed to process QR code data. Please try scanning again.')
      setLoading(false)
    }
  }

  const loadPrescriptionById = async (prescriptionId: string): Promise<PrescriptionData | null> => {
    // Check localStorage first
    const storedPrescriptions = localStorage.getItem('stored_prescriptions')
    if (storedPrescriptions) {
      const prescriptions: PrescriptionData[] = JSON.parse(storedPrescriptions)
      const found = prescriptions.find(p => p.id === prescriptionId)
      if (found) return found
    }

    // Generate sample data if not found
    if (prescriptionId.startsWith('PRESC-')) {
      const samplePrescription = QRCodeGenerator.generateSamplePrescription()
      samplePrescription.id = prescriptionId
      return samplePrescription
    }

    return null
  }

  const handleManualInput = () => {
    if (qrInput.trim()) {
      handleQRData(qrInput.trim())
    }
  }

  const resetForm = () => {
    setPrescription(null)
    setError(null)
    setQrInput('')
  }

  if (loading) {
    return (
      <div className="min-h-screen bg-gradient-to-br from-gray-50 to-gray-100 flex items-center justify-center">
        <Card className="max-w-md w-full mx-4">
          <CardContent className="p-8 text-center">
            <Loader2 className="h-12 w-12 animate-spin text-[#245064] mx-auto mb-4" />
            <h2 className="text-xl font-semibold text-gray-800 mb-2">Processing QR Code</h2>
            <p className="text-gray-600">Extracting prescription data from QR code...</p>
            <div className="mt-4 bg-gradient-to-r from-[#245064] to-[#2e6478] h-2 rounded-full animate-pulse"></div>
          </CardContent>
        </Card>
      </div>
    )
  }

  if (error) {
    return (
      <div className="min-h-screen bg-gradient-to-br from-red-50 to-red-100 flex items-center justify-center">
        <Card className="max-w-md w-full mx-4 border-red-300">
          <CardContent className="p-8 text-center">
            <ShieldX className="h-12 w-12 text-red-600 mx-auto mb-4" />
            <h2 className="text-xl font-semibold text-red-800 mb-2">QR Code Error</h2>
            <p className="text-red-600 mb-4">{error}</p>
            <div className="bg-red-100 p-4 rounded-lg border border-red-200 mb-4">
              <p className="text-sm text-red-700">
                <strong>Note:</strong> Please ensure you're scanning a valid prescription QR code 
                generated by Gonstead Chiropractic Clinic.
              </p>
            </div>
            <Button onClick={resetForm} className="bg-[#245064] hover:bg-[#1e3f4f] text-white">
              Try Again
            </Button>
          </CardContent>
        </Card>
      </div>
    )
  }

  if (prescription) {
    return (
      <DigitalPrescription 
        prescription={prescription} 
        isPublicView={true}
        showActions={true}
      />
    )
  }

  // Default landing page
  return (
    <div className="min-h-screen bg-gradient-to-br from-blue-50 to-blue-100 flex items-center justify-center">
      <Card className="max-w-lg w-full mx-4">
        <CardContent className="p-8">
          <div className="text-center mb-6">
            <QrCode className="h-16 w-16 text-[#245064] mx-auto mb-4" />
            <h1 className="text-2xl font-bold text-gray-800 mb-2">
              Gonstead Chiropractic QR Scanner
            </h1>
            <p className="text-gray-600">
              Scan or enter your prescription QR code to view your digital prescription
            </p>
          </div>

          <div className="space-y-4">
            <div>
              <label htmlFor="qr-input" className="block text-sm font-medium text-gray-700 mb-2">
                Enter QR Code Data:
              </label>
              <textarea
                id="qr-input"
                rows={4}
                className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-[#245064] focus:border-transparent"
                placeholder="Paste your QR code data here..."
                value={qrInput}
                onChange={(e) => setQrInput(e.target.value)}
              />
            </div>
            
            <Button 
              onClick={handleManualInput}
              className="w-full bg-[#245064] hover:bg-[#1e3f4f] text-white py-3"
              disabled={!qrInput.trim()}
            >
              View Prescription
            </Button>
          </div>

          <div className="mt-6 p-4 bg-blue-50 rounded-lg border border-blue-200">
            <h3 className="font-semibold text-blue-800 text-sm mb-2">How to use:</h3>
            <ul className="text-sm text-blue-700 space-y-1">
              <li>• Scan the QR code with your phone's camera</li>
              <li>• Copy and paste the QR data into the field above</li>
              <li>• Click "View Prescription" to see your digital prescription</li>
            </ul>
          </div>

          <div className="mt-4 text-center text-xs text-gray-500">
            <div className="flex items-center justify-center gap-1">
              <ShieldX className="h-3 w-3" />
              Secured by Gonstead Chiropractic Digital System
            </div>
          </div>
        </CardContent>
      </Card>
    </div>
  )
}
