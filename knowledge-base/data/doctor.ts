// Helper functions for doctor profile management
export const getDoctorById = (id: string): DoctorInfo | undefined => {
  return doctorProfile.id === id ? doctorProfile : undefined;
};

export const getDoctorExperience = (): string => {
  return `${doctorProfile.experience.years} years of specialized experience in ${doctorProfile.specialization[0]}`;
};

export const getDoctorQualifications = (): string[] => {
  return doctorProfile.qualifications.map(qual => 
    `${qual.degree} - ${qual.institution} (${qual.year})`
  );
};

export const getActiveCertifications = (): any[] => {
  const currentDate = new Date();
  return doctorProfile.certifications.filter(cert => {
    if (!cert.expiryDate) return true;
    return new Date(cert.expiryDate) > currentDate;
  });
};

export const getDoctorSpecializations = (): string[] => {
  return doctorProfile.specialization;
};

export const getDoctorLanguages = (): string[] => {
  return doctorProfile.languages;
};

export const getConsultationTypes = (): any[] => {
  return doctorProfile.consultationTypes;
};

export const getDoctorAvailability = (): string[] => {
  return doctorProfile.availableDays;
};
