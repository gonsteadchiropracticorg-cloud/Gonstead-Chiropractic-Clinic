// Helper functions for education content management
export const getEducationByCategory = (category: string): EducationContent[] => {
  return educationContent.filter(content => content.category === category);
};

export const getPopularEducationContent = (): EducationContent[] => {
  return educationContent.filter(content => content.isPopular);
};

export const searchEducationContent = (query: string): EducationContent[] => {
  const searchTerm = query.toLowerCase();
  return educationContent.filter(content => 
    content.title.toLowerCase().includes(searchTerm) ||
    content.summary.toLowerCase().includes(searchTerm) ||
    content.content.toLowerCase().includes(searchTerm) ||
    content.tags.some(tag => tag.toLowerCase().includes(searchTerm))
  );
};

export const getEducationById = (id: string): EducationContent | undefined => {
  return educationContent.find(content => content.id === id);
};

export const getEducationByDifficulty = (difficulty: string): EducationContent[] => {
  return educationContent.filter(content => content.difficulty === difficulty);
};

export const getRelatedEducation = (id: string): EducationContent[] => {
  const content = getEducationById(id);
  if (!content || !content.relatedContent) return [];
  
  return content.relatedContent
    .map(relatedId => getEducationById(relatedId))
    .filter((item): item is EducationContent => item !== undefined);
};

export const getEducationByTag = (tag: string): EducationContent[] => {
  return educationContent.filter(content => 
    content.tags.some(contentTag => contentTag.toLowerCase().includes(tag.toLowerCase()))
  );
};
